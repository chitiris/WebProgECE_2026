# =============================================================================
# UDPClient.py — Απλός πελάτης (client) UDP σε Python.
#
# Τι κάνει:
#   Διαβάζει μια πρόταση από τον χρήστη, τη στέλνει σε ένα πακέτο (datagram) στον UDPServer.py
#   (127.0.0.1, θύρα 12000) και τυπώνει την απάντηση (την ίδια πρόταση με κεφαλαία γράμματα).
#   Σε αντίθεση με το TCP, δεν γίνεται σύνδεση (connect): κάθε πακέτο στέλνεται αυτόνομα,
#   με τη διεύθυνση του παραλήπτη να δίνεται σε κάθε sendto().
#
# Εκτέλεση (πρώτα ο server, μετά ο client, σε ξεχωριστά τερματικά):
#   python UDPServer.py
#   python UDPClient.py
#
# Βασισμένο στο παράδειγμα του βιβλίου Kurose & Ross, "Computer Networking: A Top-Down Approach".
# Βασικές έννοιες: SOCK_DGRAM, sendto()/recvfrom(), διεύθυνση (IP, θύρα).
# =============================================================================

# Εισαγωγή όλων των ονομάτων του module socket (socket, AF_INET, SOCK_DGRAM κ.λπ.)
from socket import *

# Η διεύθυνση IP του διακομιστή. Το 127.0.0.1 (localhost) σημαίνει τον ίδιο υπολογιστή·
# αν ο server τρέχει σε άλλο υπολογιστή, βάλτε εδώ τη δική του διεύθυνση IP.
serverName = "127.0.0.1"

# Η θύρα στην οποία ακούει ο διακομιστής (πρέπει να είναι ίδια με του UDPServer.py)
serverPort = 12000

# Δημιουργία socket: AF_INET = διευθύνσεις IPv4, SOCK_DGRAM = πρωτόκολλο UDP (πακέτα/datagrams)
clientSocket = socket(AF_INET, SOCK_DGRAM)

# Ζητάμε από τον χρήστη να πληκτρολογήσει μια πρόταση
message = input('Input lowercase sentence:')

# Αποστολή του πακέτου στον διακομιστή: το μήνυμα μετατρέπεται σε bytes με την encode()
# και δίνεται μαζί με τη διεύθυνση του προορισμού (IP, θύρα) του server.
# Το λειτουργικό σύστημα δίνει αυτόματα στον client μια ελεύθερη θύρα αποστολής.
clientSocket.sendto(message.encode(), (serverName, serverPort))

# Λήψη της απάντησης: η recvfrom(2048) περιμένει ένα πακέτο (έως 2048 bytes) και επιστρέφει
# τα δεδομένα και τη διεύθυνση (IP, θύρα) του αποστολέα, δηλαδή του server.
# Το UDP δεν εγγυάται παράδοση: αν χαθεί το πακέτο, ο client θα περιμένει για πάντα.
modifiedMessage, serverAddress = clientSocket.recvfrom(2048)

# Μετατροπή των bytes σε string με τη decode() και εκτύπωση της απάντησης
print(modifiedMessage.decode())

# Κλείσιμο του socket του πελάτη (στο UDP δεν υπάρχει σύνδεση για τερματισμό·
# απλώς ελευθερώνεται η θύρα)
clientSocket.close()

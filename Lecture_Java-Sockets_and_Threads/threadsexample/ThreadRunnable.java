/*
 * ThreadRunnable.java — Ο κώδικας που εκτελούν τα νήματα του παραδείγματος MyThread.
 *
 * Η κλάση αυτή δεν έχει main, άρα δεν εκτελείται μόνη της. Τη χρησιμοποιεί η κλάση MyThread,
 * που δημιουργεί δύο νήματα με αυτό το αντικείμενο.
 *
 * Υλοποιεί το interface Runnable, που απαιτεί μία μόνο μέθοδο: την run().
 * Ο τρόπος αυτός (implements Runnable) προτιμάται συχνά από το "extends Thread",
 * γιατί η κλάση μένει ελεύθερη να κληρονομήσει από άλλη κλάση και ο κώδικας (Runnable)
 * διαχωρίζεται από τον μηχανισμό εκτέλεσης (Thread).
 */
public class ThreadRunnable implements Runnable {
	    // Η μέθοδος run() περιέχει τον κώδικα που θα εκτελέσει κάθε νήμα όταν κληθεί η start()
	    public void run() {
	        // Μήνυμα όταν το νήμα ξεκινά την εκτέλεσή του
	        System.out.println("Thread is under Running...");

	        // Βρόχος που εκτελείται 100 φορές (i = 1 έως 100)
	        for (int i = 1; i <= 100; i++) {
	            // Τυπώνουμε το όνομα του νήματος που εκτελεί αυτή τη στιγμή τον κώδικα και την τιμή του i.
	            // Το ίδιο αντικείμενο εκτελείται από δύο νήματα, οπότε η getName() δείχνει ποιο τύπωσε κάθε γραμμή.
	            // Η μεταβλητή i είναι τοπική, άρα κάθε νήμα έχει το δικό του αντίγραφο και μετράει ανεξάρτητα.
	            System.out.println("Thread=" + Thread.currentThread().getName() + "  i=" + i);
	        }
	    }

}
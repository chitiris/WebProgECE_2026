/*
 * MyThread.java — Εισαγωγή στα νήματα (threads) στη Java.
 *
 * Τι κάνει:
 *   Δημιουργεί δύο νήματα (Thread1 και Thread2) που εκτελούν τον ίδιο κώδικα: τη μέθοδο run()
 *   της κλάσης ThreadRunnable (τυπώνει έναν μετρητή από 1 έως 100).
 *   Στην έξοδο φαίνεται η παρεμβολή (interleaving) των δύο νημάτων: οι γραμμές τους
 *   ανακατεύονται, γιατί εκτελούνται ταυτόχρονα και τη σειρά την αποφασίζει ο χρονοπρογραμματιστής
 *   (scheduler) της JVM/του λειτουργικού. Κάθε εκτέλεση μπορεί να δώσει διαφορετική σειρά.
 *
 * Εκτέλεση: javac *.java  και μετά  java MyThread
 *
 * Βασικές έννοιες: Runnable, Thread, start() έναντι run(), όνομα νήματος.
 */

public class MyThread {
    public static void main(String[] args) {
        // Δημιουργούμε ένα αντικείμενο της κλάσης ThreadRunnable.
        // Αυτό ΔΕΝ είναι νήμα· περιέχει μόνο τον κώδικα (run()) που θα εκτελέσουν τα νήματα.
        ThreadRunnable threadObject = new ThreadRunnable();

        // Δημιουργούμε δύο νήματα που χρησιμοποιούν το ίδιο αντικείμενο threadObject ως κώδικα εκτέλεσης.
        // Η δεύτερη παράμετρος είναι το όνομα του νήματος, που επιστρέφει η Thread.currentThread().getName().
        Thread thread1 = new Thread(threadObject, "Thread1");
        Thread thread2 = new Thread(threadObject, "Thread2");

        // Ενημερώνουμε ότι το Thread1 πρόκειται να ξεκινήσει
        System.out.println("Thread 1 about to start...");
        // Ξεκινάμε το Thread1. Η start() δημιουργεί νέο νήμα εκτέλεσης, το οποίο καλεί τη run().
        // Η start() επιστρέφει αμέσως, οπότε η main συνεχίζει παράλληλα με το Thread1.
        // (Αν καλούσαμε απευθείας τη run(), ο κώδικας θα εκτελούνταν στο ίδιο νήμα με τη main,
        // σαν απλή κλήση μεθόδου, χωρίς καμία ταυτόχρονη εκτέλεση.)
        thread1.start();

        // Ενημερώνουμε ότι το Thread2 πρόκειται να ξεκινήσει
        System.out.println("Thread 2 about to start...");
        // Ξεκινάμε το Thread2. Από εδώ και πέρα τα δύο νήματα τρέχουν ταυτόχρονα.
        thread2.start();
        // Η main τελειώνει εδώ, αλλά το πρόγραμμα συνεχίζει μέχρι να τελειώσουν και τα δύο νήματα.
    }
}
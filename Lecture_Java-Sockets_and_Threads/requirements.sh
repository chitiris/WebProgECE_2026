#!/bin/bash
# =============================================================================
# requirements.sh — Εγκατάσταση Java (JDK 25) σε Ubuntu / WSL
#
# Εγκαθιστά το OpenJDK 25 (έκδοση LTS), που περιέχει:
#   javac : τον compiler, που μετατρέπει τα αρχεία .java σε .class
#   java  : το περιβάλλον εκτέλεσης (JVM), που τρέχει τα προγράμματα
#
# Εκτέλεση (από τον φάκελο Lecture_Java-Sockets_and_Threads):
#   bash requirements.sh
# =============================================================================

# Σταματάμε αμέσως αν κάποια εντολή αποτύχει
set -e

# Ενημέρωση της λίστας πακέτων του Ubuntu
sudo apt update -y

# Εγκατάσταση του JDK 25 (το "headless" δεν περιλαμβάνει γραφικό περιβάλλον, που δεν χρειάζεται εδώ)
sudo apt install -y openjdk-25-jdk-headless

# Έλεγχος: και οι δύο εντολές πρέπει να δείχνουν έκδοση 25
java -version
javac -version
